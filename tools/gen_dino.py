#!/usr/bin/env python3
"""Generate art/dino/*.svg (the vector art) and f1-tracker/f1_dino_data.h: the dinosaur's seven poses (facing right) and
the speech bubble's two pointers, as LVGL RGB565A8 images (an RGB565 plane then an 8-bit alpha plane,
straight alpha), antialiased. The device mirrors them in memory when the dinosaur walks left."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dino_art as art

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "f1-tracker", "f1_dino_data.h")


def planes(im):
    px = im.tobytes()
    rgb, alpha = bytearray(), bytearray()
    for i in range(0, len(px), 4):
        r, g, b, a = px[i:i + 4]
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        rgb += bytes((v & 0xFF, v >> 8))
        alpha.append(a)
    return bytes(rgb) + bytes(alpha)


def arr(name, data, per_line=24):
    out = [f"inline constexpr uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), per_line):
        out.append("  " + ",".join(str(b) for b in data[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def write_svgs():
    """The vector art itself: art/dino/pose-N.svg and the two bubble pointers."""
    d = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "art", "dino")
    os.makedirs(d, exist_ok=True)
    for p in range(art.N_POSES):
        open(os.path.join(d, f"pose-{p}.svg"), "w").write(art.svg(p) + "\n")
    for flip in (False, True):
        open(os.path.join(d, f"bubble-tail-{'left' if flip else 'right'}.svg"), "w").write(art.tail_svg(flip) + "\n")


def main():
    write_svgs()
    lines = ["#pragma once",
             "// GENERATED by tools/gen_dino.py - do not edit.",
             "//",
             "// The walking dinosaur: seven poses (four steps, standing, mouth half open, mouth open), facing right,",
             f"// {art.SW}x{art.SH}, and the speech bubble's two pointers, as LVGL RGB565A8 images (an RGB565 plane, then an",
             "// 8-bit alpha plane), antialiased. A generic green dinosaur: no F1, team or series mark.",
             "#include <cstdint>",
             "",
             "namespace f1 {",
             "namespace dino {",
             f"inline constexpr int DATA_W = {art.SW}, DATA_H = {art.SH}, TAIL_W = 22, TAIL_H = 12;", ""]
    for p in range(art.N_POSES):
        lines.append(arr(f"POSE{p}", planes(art.sprite(p))))
        lines.append("")
    lines.append("inline const uint8_t *const POSES[%d] = {%s};" % (art.N_POSES, ", ".join(f"POSE{p}" for p in range(art.N_POSES))))
    lines.append("")
    for flip in (False, True):
        lines.append(arr("TAIL_" + ("L" if flip else "R"), planes(art.tail_image(flip)), 22))
        lines.append("")
    lines.append("}  // namespace dino")
    lines.append("}  // namespace f1")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(OUT)}  {os.path.getsize(OUT) // 1024} KB source")


if __name__ == "__main__":
    main()
