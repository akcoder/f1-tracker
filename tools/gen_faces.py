#!/usr/bin/env python3
"""Generate art/faces.json and f1-tracker/f1_faces.h: where the face is in every compiled portrait.

Carl (MOTION-8) bites a person in the face, so the firmware has to know where it is. Each of the
240x320 portraits in f1_portraits.h is run through OpenCV's Haar face detectors (frontal, then profile,
and mirrored); the largest hit is the face, as a box from the brow to the chin. The ones the detector
missed or got wrong were looked at by eye on a contact sheet and are given by hand in OVERRIDE below
(the whole set was checked that way: every box sits on the face).

Needs opencv-python-headless 4.x and pillow (not part of the build, only of this tool):
  python3 -m venv /tmp/cv && /tmp/cv/bin/pip install opencv-python-headless==4.10.0.84 "numpy<2" pillow
  /tmp/cv/bin/python tools/gen_faces.py            # --sheet out.png draws the boxes for a look

A headshot fetched at runtime (f1_headshot.h) is not in the repository; the F1 media server frames them
all alike (a studio shot, the face centred and high), so one box serves for them, in the 206 px picture.
"""
import argparse, io, json, os, re, sys
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "f1-tracker", "f1_portraits.h")
OUT = os.path.join(ROOT, "f1-tracker", "f1_faces.h")
JSON = os.path.join(ROOT, "art", "faces.json")
PW, PH = 240, 320
HEADSHOT_FACE = (70, 20, 62, 82)       # x, y, w, h in the 206x206 headshot

# By hand, where the detector found nothing or the wrong thing: x, y, w, h in the 240x320 portrait.
OVERRIDE = {
    "bearman": (50, 60, 90, 90),
    "rindt": (80, 50, 80, 100),
    "button": (80, 25, 120, 140),
    "hill": (55, 60, 130, 140),
    "raikkonen": (55, 85, 100, 95),
}


def portraits():
    src = open(SRC).read()
    for did, name in re.findall(r'\{"([a-z_0-9]+)", IMG_([A-Z_0-9]+), \d+,', src):
        m = re.search(r'IMG_%s\[\d+\] = \{(.*?)\};' % name, src, re.S)
        yield did, Image.open(io.BytesIO(bytes(int(x) for x in re.findall(r"\d+", m.group(1))))).convert("RGB")


def detect(im):
    import cv2, numpy
    g = cv2.cvtColor(numpy.array(im), cv2.COLOR_RGB2GRAY)
    cs = [cv2.CascadeClassifier(cv2.data.haarcascades + n) for n in
          ("haarcascade_frontalface_default.xml", "haarcascade_frontalface_alt2.xml", "haarcascade_profileface.xml")]
    best = None
    for i, c in enumerate(cs):
        for flip in (False, True):
            if i < 2 and flip:
                continue
            for (x, y, w, h) in c.detectMultiScale(cv2.flip(g, 1) if flip else g, 1.08, 4, minSize=(40, 40)):
                if flip:
                    x = g.shape[1] - x - w
                if best is None or w > best[2]:
                    best = (int(x), int(y), int(w), int(h))
    return best


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sheet", help="also draw the boxes on a contact sheet")
    a = ap.parse_args()
    faces, ims = {}, {}
    for did, im in portraits():
        ims[did] = im
        box = OVERRIDE.get(did) or detect(im)
        if box is None:
            sys.exit(f"{did}: no face found and no override")
        faces[did] = list(box)
    os.makedirs(os.path.dirname(JSON), exist_ok=True)
    json.dump({"portrait_size": [PW, PH], "headshot_face": list(HEADSHOT_FACE), "faces": faces}, open(JSON, "w"), indent=1, sort_keys=True)
    lines = ["#pragma once", "// GENERATED by tools/gen_faces.py - do not edit.", "//",
             "// Where the face is in each compiled portrait (240x320): a box from the brow to the chin. Carl bites it",
             "// (MOTION-8). Found by face detection, every one checked by eye; art/faces.json has the same numbers.",
             "#include <cstdint>", "#include <cstring>", "", "namespace f1 {", "namespace faces {", "",
             "struct Face {", "  const char *driver_id;", "  uint16_t x, y, w, h;", "};", "",
             f"// the F1 media server's headshots (206x206), all framed alike", f"inline constexpr Face HEADSHOT = {{\"\", {HEADSHOT_FACE[0]}, {HEADSHOT_FACE[1]}, {HEADSHOT_FACE[2]}, {HEADSHOT_FACE[3]}}};", "",
             f"inline constexpr Face F[{len(faces)}] = {{"]
    for did in sorted(faces):
        x, y, w, h = faces[did]
        lines.append(f'    {{"{did}", {x}, {y}, {w}, {h}}},')
    lines += ["};", "", "inline const Face *find(const char *driver_id) {", "  if (driver_id == nullptr || !*driver_id) return nullptr;",
              f"  for (const auto &f : F)", "    if (std::strcmp(driver_id, f.driver_id) == 0) return &f;", "  return nullptr;", "}", "",
              "}  // namespace faces", "}  // namespace f1", ""]
    open(OUT, "w").write("\n".join(lines))
    print(f"{len(faces)} faces -> {os.path.relpath(OUT, ROOT)}")
    if a.sheet:
        ids = sorted(faces); cw, ch, cols = 150, 200, 8
        sh = Image.new("RGB", (cols * cw, ((len(ids) + cols - 1) // cols) * ch), "black")
        for i, k in enumerate(ids):
            im = ims[k].resize((cw, ch)); d = ImageDraw.Draw(im); s = cw / PW; b = faces[k]
            d.rectangle([b[0] * s, b[1] * s, (b[0] + b[2]) * s, (b[1] + b[3]) * s], outline=(0, 255, 0), width=2)
            d.text((3, 3), k[:14], fill=(255, 255, 0)); sh.paste(im, ((i % cols) * cw, (i // cols) * ch))
        sh.save(a.sheet)


if __name__ == "__main__":
    main()
