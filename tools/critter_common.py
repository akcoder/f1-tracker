#!/usr/bin/env python3
"""What the dinosaur (dino_art.py, gen_dino.py) and the toucan (toucan_art.py, gen_toucan.py) share:
the random numbers (f1_critterlogic.h's twin), rasterising vector art, the firmware's RGB565A8 data
arrays, and drawing a frame of a visit with its speech bubble (f1_critter.h's picture)."""
import io, subprocess
from PIL import Image, ImageDraw

GAP_MIN_MS, GAP_MAX_MS = 3 * 60000, 12 * 60000      # between visits


class Rng:
    """xorshift32: the same numbers on the device and here."""
    def __init__(self, seed):
        self.s = (seed or 1) & 0xFFFFFFFF

    def next(self):
        x = self.s
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        self.s = x
        return (x >> 8) / 16777216.0


def next_gap_ms(seed):
    return GAP_MIN_MS + int(Rng(seed).next() * (GAP_MAX_MS - GAP_MIN_MS))


def raster(svg_text, w, h):
    """An SVG as an antialiased RGBA image (rsvg-convert)."""
    out = subprocess.run(["rsvg-convert", "-w", str(w), "-h", str(h)], input=svg_text.encode(), capture_output=True, check=True).stdout
    return Image.open(io.BytesIO(out)).convert("RGBA")


def planes(im):
    """An RGBA image as LVGL RGB565A8: an RGB565 plane, then an 8-bit straight-alpha plane."""
    px = im.tobytes()
    rgb, alpha = bytearray(), bytearray()
    for i in range(0, len(px), 4):
        r, g, b, a = px[i:i + 4]
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        rgb += bytes((v & 0xFF, v >> 8))
        alpha.append(a)
    return bytes(rgb) + bytes(alpha)


def arr(name, data, per_line=24):
    out = [f"inline constexpr uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), per_line):
        out.append("  " + ",".join(str(b) for b in data[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def write_header(path, comment, ns, consts, art):
    """f1-tracker/f1_<name>_data.h: the poses as arrays, and POSES[] to index them."""
    lines = ["#pragma once", "// GENERATED by tools/gen_" + ns + ".py - do not edit.", "//"] + ["// " + c for c in comment] + [
        "#include <cstdint>", "", "namespace f1 {", f"namespace {ns} {{", consts, ""]
    for p in range(art.N_POSES):
        lines += [arr(f"POSE{p}", planes(art.sprite(p))), ""]
    lines.append("inline const uint8_t *const POSES[%d] = {%s};" % (art.N_POSES, ", ".join(f"POSE{p}" for p in range(art.N_POSES))))
    lines.append("")
    return lines


def bubble(text, font):
    """The speech bubble as f1_critter.h builds it: a 10 px rounded rectangle, 2 px orange border, mono16."""
    tw = int(font.getlength(text))
    w, h = tw + 24, 16 + 10 + 4          # 10 px side padding + 2 px border; the font's line + 5 px padding
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
    d.rounded_rectangle([0, 0, w - 1, h - 1], radius=10, fill=(0xF2, 0xF5, 0xFC), outline=(0xFF, 0x8A, 0x1F), width=2)
    d.text((w // 2, h // 2), text, font=font, fill=(0x10, 0x14, 0x20), anchor="mm")
    return im


def frame(bg, art, poses, tails, visit, t_ms, font, screen_w):
    """One frame of a visit over `bg`, as f1_critter.h draws it: the sprite (mirrored going left), then
    over its head the bubble and its pointer."""
    x, y, pose, shown = visit.at(t_ms)
    img = bg.copy()
    sp = poses[pose]
    if visit.flip:
        sp = sp.transpose(Image.FLIP_LEFT_RIGHT)
    img.paste(sp, (x, y), sp)
    if shown:
        b = bubble(art.WORDS[visit.word], font)
        bx = x - 6 if visit.flip else x + art.SW + 6 - b.width
        bx = max(4, min(screen_w - 4 - b.width, bx))
        by = y - b.height - 12 + 4
        img.paste(b, (bx, by), b)
        tail = tails[1 if visit.flip else 0]
        tx = bx + 14 if visit.flip else bx + b.width - 22 - 14
        img.paste(tail, (tx, by + b.height - 2), tail)
    return img
